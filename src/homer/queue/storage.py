class QueueStorage:
    def __init__(self, config, db: Optional[BaseDB] = None):
        self.config = config
        self._external_db = db is not None
        self.db = db or self._build_db()
        if not self.db.is_connected:
            self.db.connect()
        self.init_schema()

    def _build_db(self) -> BaseDB:
        sched_cfg = self.config.get('scheduler', {}) or {}
        driver = sched_cfg.get('storage', 'sqlite')
        conn_cfg = sched_cfg.get(driver) or self.config.get(f'databases.{driver}')
        if driver == 'sqlite':
            if not conn_cfg:
                conn_cfg = {'path': 'var/scheduler.db'}
            elif 'path' not in conn_cfg:
                conn_cfg = dict(conn_cfg, path='var/scheduler.db')
        return connect(driver, conn_cfg)

    def _driver(self):
        return self.db.driver_name

    def _ph(self, idx):
        style = self.db._placeholder_style
        if style == ':name':
            return f':{idx + 1}'
        if style == '?':
            return '?'
        return '%s'

    def _ph_list(self, n):
        return ', '.join(self._ph(i) for i in range(n))

    def _host_id(self):
        return f"{socket.gethostname()}:{os.getpid()}"

    def _bool(self, v):
        if self._driver() == 'oracle':
            return 1 if v else 0
        return bool(v)

    def init_schema(self):
        driver = self._driver()
        ddl = DDL.get(driver)
        if not ddl:
            raise DBError(f"Нет DDL очереди для драйвера '{driver}'")
        if driver == 'oracle':
            cur = self.db.cursor()
            try:
                cur.execute(ddl)
            finally:
                try:
                    cur.close()
                except Exception:
                    pass
        else:
            for stmt in [s.strip() for s in ddl.split(';') if s.strip()]:
                self.db.execute(stmt)
        self.db.commit()

    # ─────────────────── Push ───────────────────

    def push(self, job: QueueJob) -> int:
        job.created_at = job.created_at or datetime.now()
        driver = self._driver()

        cols = (
            "command, args, priority, status, created_at, run_at, "
            "parent_job_id, triggered_by, attempts, max_attempts, "
            "retry_delay, timeout_sec"
        )
        values = [
            job.command,
            job.args_json(),
            job.priority,
            job.status or JobStatus.PENDING,
            job.created_at,
            job.run_at,
            job.parent_job_id,
            job.triggered_by,
            job.attempts,
            job.max_attempts,
            job.retry_delay,
            job.timeout_sec,
        ]
        n = len(values)
        sql = f"INSERT INTO homer_queue ({cols}) VALUES ({self._ph_list(n)})"

        if driver == 'postgres':
            sql += " RETURNING id"
            row = self.db.fetchone(sql, values)
            self.db.commit()
            return row[0] if not isinstance(row, dict) else next(iter(row.values()))

        if driver == 'oracle':
            sql += " RETURNING id INTO :out_id"
            cur = self.db.cursor()
            out_id = cur.var(int)
            cur.execute(sql, values + [out_id])
            self.db.commit()
            try:
                cur.close()
            except Exception:
                pass
            return int(out_id.getvalue()[0])

        cur = self.db.execute(sql, values)
        self.db.commit()
        return cur.lastrowid

    # ─────────────────── Get / List ───────────────────

    def get(self, job_id):
        row = self.db.fetchone(
            f"SELECT * FROM homer_queue WHERE id = {self._ph(0)}",
            [job_id],
            dictionary=True,
        )
        return QueueJob.from_row(row) if row else None

    def list(self, status=None, limit=100):
        if status:
            sql = (
                f"SELECT * FROM homer_queue WHERE status = {self._ph(0)} "
                f"ORDER BY priority DESC, id ASC"
            )
            rows = self.db.fetchall(sql, [status], dictionary=True)
        else:
            rows = self.db.fetchall(
                "SELECT * FROM homer_queue ORDER BY priority DESC, id ASC",
                dictionary=True,
            )
        return [QueueJob.from_row(r) for r in rows[:limit]]

    def stats(self):
        rows = self.db.fetchall(
            "SELECT status, COUNT(*) AS cnt FROM homer_queue GROUP BY status",
            dictionary=True,
        )
        result = dict.fromkeys(
            (
                JobStatus.PENDING,
                JobStatus.RUNNING,
                JobStatus.DONE,
                JobStatus.FAILED,
                JobStatus.CANCELED,
                JobStatus.TIMEOUT,
            ),
            0,
        )
        for r in rows:
            st = r['status'] if isinstance(r, dict) else r[0]
            cnt = r['cnt'] if isinstance(r, dict) else r[1]
            result[st] = int(cnt)
        return result

    # ─────────────────── Атомарный захват ───────────────────

    def acquire_next(self, lease_seconds=300):
        """
        Атомарно берёт следующий pending-job и увеличивает attempts.
        Attempts инкрементируется ЗДЕСЬ — это защищает от «вечных retry»,
        если воркер упал и lease истёк: следующая попытка уже учтена.
        """
        now = datetime.now()
        lease_until = now + timedelta(seconds=lease_seconds)
        run_id = str(uuid.uuid4())
        locked_by = self._host_id()
        driver = self._driver()

        base_set = (
            f"  status = {self._ph(0)}, "
            f"  run_id = {self._ph(1)}, "
            f"  locked_by = {self._ph(2)}, "
            f"  lease_until = {self._ph(3)}, "
            f"  started_at = {self._ph(4)}, "
            f"  last_attempt_at = {self._ph(5)}, "
            f"  attempts = attempts + 1 "
        )

        where_sub = (
            f"  ((status = {self._ph(6)} AND (run_at IS NULL OR run_at <= {self._ph(7)})) "
            f"   OR (status = {self._ph(8)} AND lease_until < {self._ph(9)})) "
        )

        if driver == 'postgres':
            sql = (
                f"UPDATE homer_queue SET {base_set} "
                f"WHERE id = ("
                f"  SELECT id FROM homer_queue WHERE {where_sub}"
                f"  ORDER BY priority DESC, id ASC LIMIT 1 "
                f"  FOR UPDATE SKIP LOCKED"
                f") RETURNING *"
            )
            params = [
                JobStatus.RUNNING,
                run_id,
                locked_by,
                lease_until,
                now,
                now,
                JobStatus.PENDING,
                now,
                JobStatus.RUNNING,
                now,
            ]
            row = self.db.fetchone(sql, params, dictionary=True)
            self.db.commit()
            return QueueJob.from_row(row) if row else None

        if driver == 'sqlite':
            sql = (
                f"UPDATE homer_queue SET {base_set} "
                f"WHERE id = ("
                f"  SELECT id FROM homer_queue WHERE {where_sub}"
                f"  ORDER BY priority DESC, id ASC LIMIT 1"
                f")"
            )
            params = [
                JobStatus.RUNNING,
                run_id,
                locked_by,
                lease_until,
                now,
                now,
                JobStatus.PENDING,
                now,
                JobStatus.RUNNING,
                now,
            ]
            cur = self.db.execute(sql, params)
            self.db.commit()
            if cur.rowcount != 1:
                return None
            row = self.db.fetchone(
                f"SELECT * FROM homer_queue WHERE run_id = {self._ph(0)}",
                [run_id],
                dictionary=True,
            )
            return QueueJob.from_row(row) if row else None

        # Oracle / прочие
        try:
            with self.db.transaction():
                cur = self.db.cursor()
                sql_sel = (
                    f"SELECT id FROM homer_queue "
                    f"WHERE ((status = {self._ph(0)} AND (run_at IS NULL OR run_at <= {self._ph(1)})) "
                    f"   OR (status = {self._ph(2)} AND lease_until < {self._ph(3)})) "
                    f"ORDER BY priority DESC, id ASC "
                    f"FETCH FIRST 1 ROWS ONLY"
                )
                cur.execute(sql_sel, [JobStatus.PENDING, now, JobStatus.RUNNING, now])
                r = cur.fetchone()
                if not r:
                    return None
                candidate_id = r[0] if not isinstance(r, dict) else next(iter(r.values()))

                cur.execute(
                    f"UPDATE homer_queue SET {base_set} WHERE id = {self._ph(10)}",
                    [
                        JobStatus.RUNNING,
                        run_id,
                        locked_by,
                        lease_until,
                        now,
                        now,
                        JobStatus.PENDING,
                        now,
                        JobStatus.RUNNING,
                        now,
                        candidate_id,
                    ],
                )
        except DBError:
            return None

        row = self.db.fetchone(
            f"SELECT * FROM homer_queue WHERE id = {self._ph(0)}",
            [candidate_id],
            dictionary=True,
        )
        return QueueJob.from_row(row) if row else None

    def heartbeat(self, job_id, run_id, lease_seconds=300):
        lease_until = datetime.now() + timedelta(seconds=lease_seconds)
        cur = self.db.execute(
            f"UPDATE homer_queue SET lease_until = {self._ph(0)} "
            f"WHERE id = {self._ph(1)} AND run_id = {self._ph(2)}",
            [lease_until, job_id, run_id],
        )
        self.db.commit()
        return cur.rowcount == 1

    # ─────────────────── Finish / Retry ───────────────────

    def finish(self, job_id, run_id, status, result=None, exit_code=None, error=None):
        """
        Завершает job.
        Если status='failed' и attempts < max_attempts — перепоставляем в очередь.
        """
        now = datetime.now()
        job = self.get(job_id)
        if job is None:
            return

        if status == JobStatus.FAILED and job.attempts < job.max_attempts:
            retry_at = now + timedelta(seconds=job.retry_delay)
            sql = (
                f"UPDATE homer_queue SET "
                f"  status = {self._ph(0)}, "
                f"  run_at = {self._ph(1)}, "
                f"  error = {self._ph(2)}, "
                f"  result = {self._ph(3)}, "
                f"  exit_code = {self._ph(4)}, "
                f"  locked_by = NULL, "
                f"  lease_until = NULL, "
                f"  run_id = NULL, "
                f"  started_at = NULL, "
                f"  cancel_requested = {self._ph(5)} "
                f"WHERE id = {self._ph(6)} AND run_id = {self._ph(7)}"
            )
            self.db.execute(
                sql,
                [
                    JobStatus.PENDING,
                    retry_at,
                    error,
                    result,
                    exit_code,
                    self._bool(False),
                    job_id,
                    run_id,
                ],
            )
            self.db.commit()
            return

        sql = (
            f"UPDATE homer_queue SET "
            f"  status = {self._ph(0)}, "
            f"  result = {self._ph(1)}, "
            f"  exit_code = {self._ph(2)}, "
            f"  error = {self._ph(3)}, "
            f"  finished_at = {self._ph(4)}, "
            f"  locked_by = NULL, "
            f"  lease_until = NULL "
            f"WHERE id = {self._ph(5)} AND run_id = {self._ph(6)}"
        )
        self.db.execute(
            sql,
            [
                status,
                result,
                exit_code,
                error,
                now,
                job_id,
                run_id,
            ],
        )
        self.db.commit()

    # ─────────────────── Cancel ───────────────────

    def request_cancel(self, job_id):
        cur = self.db.execute(
            f"UPDATE homer_queue SET cancel_requested = {self._ph(0)} "
            f"WHERE id = {self._ph(1)} AND status = {self._ph(2)}",
            [self._bool(True), job_id, JobStatus.RUNNING],
        )
        self.db.commit()
        return cur.rowcount == 1

    def is_cancel_requested(self, job_id):
        row = self.db.fetchone(
            f"SELECT cancel_requested FROM homer_queue WHERE id = {self._ph(0)}",
            [job_id],
            dictionary=True,
        )
        if not row:
            return False
        v = row['cancel_requested'] if isinstance(row, dict) else row[0]
        return bool(v)

    def cancel(self, job_id, cascade=True, reason=None):
        """
        Отменяет job. Если cascade=True, рекурсивно отменяет потомков.
        Возвращает число отменённых.
        """
        ids = [job_id]
        if cascade:
            ids += self._descendants(job_id)

        now = datetime.now()
        reason = reason or "canceled"

        # pending → canceled
        in_ph = ', '.join(self._ph(i) for i in range(len(ids)))
        sql = (
            f"UPDATE homer_queue SET "
            f"  status = {self._ph(len(ids))}, "
            f"  finished_at = {self._ph(len(ids) + 1)}, "
            f"  error = {self._ph(len(ids) + 2)} "
            f"WHERE id IN ({in_ph}) AND status = {self._ph(len(ids) + 3)}"
        )
        params = [
            JobStatus.CANCELED,
            now,
            reason,
            *ids,
            JobStatus.PENDING,
        ]
        cur = self.db.execute(sql, params)
        self.db.commit()
        count = cur.rowcount

        # running → пометить cancel_requested
        sql2 = (
            f"UPDATE homer_queue SET cancel_requested = {self._ph(len(ids))} "
            f"WHERE id IN ({in_ph}) AND status = {self._ph(len(ids) + 1)}"
        )
        params2 = [self._bool(True), *ids, JobStatus.RUNNING]
        self.db.execute(sql2, params2)
        self.db.commit()

        return count

    def _descendants(self, job_id):
        result = []
        frontier = [job_id]
        seen = {job_id}
        while frontier:
            placeholders = self._ph_list(len(frontier))
            sql = f"SELECT id FROM homer_queue WHERE parent_job_id IN ({placeholders})"
            rows = self.db.fetchall(sql, frontier, dictionary=True)
            next_frontier = []
            for r in rows:
                cid = r['id'] if isinstance(r, dict) else r[0]
                if cid in seen:
                    continue
                seen.add(cid)
                result.append(cid)
                next_frontier.append(cid)
            frontier = next_frontier
        return result

    # ─────────────────── Retry / Purge ───────────────────

    def retry(self, job_id):
        """Ручной retry: сброс и в pending"""
        self.db.execute(
            f"UPDATE homer_queue SET "
            f"  status = {self._ph(0)}, "
            f"  attempts = 0, "
            f"  error = NULL, "
            f"  run_at = NULL, "
            f"  locked_by = NULL, "
            f"  lease_until = NULL, "
            f"  run_id = NULL, "
            f"  cancel_requested = {self._ph(1)} "
            f"WHERE id = {self._ph(2)}",
            [JobStatus.PENDING, self._bool(False), job_id],
        )
        self.db.commit()

    def purge(self, older_than_seconds=86400):
        cutoff = datetime.now() - timedelta(seconds=older_than_seconds)
        sql = (
            f"DELETE FROM homer_queue WHERE "
            f"  status IN ({self._ph(0)}, {self._ph(1)}, {self._ph(2)}, {self._ph(3)}) "
            f"  AND finished_at < {self._ph(4)}"
        )
        cur = self.db.execute(
            sql,
            [
                JobStatus.DONE,
                JobStatus.FAILED,
                JobStatus.CANCELED,
                JobStatus.TIMEOUT,
                cutoff,
            ],
        )
        self.db.commit()
        return cur.rowcount

    def close(self):
        if not self._external_db:
            self.db.close()

@dataclass
class User:
    id: int
    username: str
    display_name: str = ''
    email: str = ''
    locale: Optional[str] = None
    provider: str = 'local'
    enabled: bool = True
    roles: list[str] = field(default_factory=list)
    permissions: set[str] = field(default_factory=set)

    def has_perm(self, perm: str) -> bool:
        return perm in self.permissions or '*' in self.permissions


# ─────────── Хэширование паролей ───────────

def hash_password(password: str, *, salt: bytes | None = None) -> str:
    """
    PBKDF2-HMAC-SHA256. Формат: pbkdf2_sha256$iterations$salt_hex$hash_hex
    """
    iterations = 200_000
    salt = salt or secrets.token_bytes(16)
    h = hashlib.pbkdf2_hmac('sha256', password.encode('utf-8'), salt, iterations)
    return f"pbkdf2_sha256${iterations}${salt.hex()}${h.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        algo, iter_s, salt_hex, hash_hex = stored.split('$')
        if algo != 'pbkdf2_sha256':
            return False
        iterations = int(iter_s)
        salt = bytes.fromhex(salt_hex)
        expected = bytes.fromhex(hash_hex)
        h = hashlib.pbkdf2_hmac('sha256', password.encode('utf-8'), salt, iterations)
        return hmac.compare_digest(h, expected)
    except Exception:
        return False


class AuthStore:
    def __init__(self, config, db=None):
        self.config = config
        self._external_db = db is not None
        self.db = db or self._build_db()
        if not self.db.is_connected:
            self.db.connect()
        self.init_schema()
        self._bootstrap_defaults()

    # ─────────── БД ───────────

    def _build_db(self):
        sched_cfg = self.config.get('scheduler', {}) or {}
        driver = sched_cfg.get('storage', 'sqlite')
        conn_cfg = sched_cfg.get(driver) or self.config.get(f'databases.{driver}')
        if driver == 'sqlite':
            if not conn_cfg:
                conn_cfg = {'path': 'var/cache/homer.db'}
            elif 'path' not in conn_cfg:
                conn_cfg = dict(conn_cfg, path='var/cache/homer.db')
        return connect(driver, conn_cfg)

    def _driver(self):
        return self.db.driver_name

    def _ph(self, idx):
        style = self.db._placeholder_style
        if style == ':name':
            return f':{idx + 1}'
        if style == '?':
            return '?'
        return '%s'

    def _bool(self, v):
        return 1 if v else 0 if self._driver() == 'oracle' else bool(v)

    def init_schema(self):
        ddl = DDL.get(self._driver())
        if not ddl:
            raise DBError(f"No DDL for {self._driver()}")
        if self._driver() == 'oracle':
            for block in ddl.split(';'):
                block = block.strip()
                if not block:
                    continue
                cur = self.db.cursor()
                try:
                    cur.execute(block)
                except Exception:
                    pass
                finally:
                    try: cur.close()
                    except Exception: pass
        else:
            for stmt in [s.strip() for s in ddl.split(';') if s.strip()]:
                self.db.execute(stmt)
        self.db.commit()

    # ─────────── Bootstrap ───────────

    def _bootstrap_defaults(self):
        """Создаёт встроенные роли и первого админа."""
        from homer.auth.permissions import BUILTIN_ROLES

        for name, spec in BUILTIN_ROLES.items():
            self.upsert_role(
                name=name,
                display_name=spec['display_name'],
                permissions=spec['permissions'],
                builtin=True,
            )

        # Первый пользователь — из config или admin/admin
        cfg_user = self.config.get('webui.auth.user')
        cfg_pass = self.config.get('webui.auth.password')

        if self.count_users() == 0:
            username = cfg_user or 'admin'
            password = cfg_pass or 'admin'
            uid = self.create_user(username, password, provider='local')
            self.assign_role(uid, 'admin')

    # ─────────── Пользователи ───────────

    def count_users(self) -> int:
        row = self.db.fetchone("SELECT COUNT(*) FROM homer_users")
        if not row:
            return 0
        return row[0] if not isinstance(row, dict) else next(iter(row.values()))

    def get_user_by_name(self, username: str) -> Optional[User]:
        row = self.db.fetchone(
            f"SELECT * FROM homer_users WHERE username = {self._ph(0)}",
            [username], dictionary=True,
        )
        if not row:
            return None
        return self._row_to_user(row)

    def get_user(self, user_id: int) -> Optional[User]:
        row = self.db.fetchone(
            f"SELECT * FROM homer_users WHERE id = {self._ph(0)}",
            [user_id], dictionary=True,
        )
        if not row:
            return None
        return self._row_to_user(row)

    def list_users(self) -> list[User]:
        rows = self.db.fetchall(
            "SELECT * FROM homer_users ORDER BY username",
            dictionary=True,
        )
        return [self._row_to_user(r) for r in rows]

    def create_user(self, username: str, password: str | None = None,
                    *, display_name: str = "", email: str = "",
                    provider: str = "local",
                    locale: Optional[str] = None) -> int:
        now = datetime.now()
        pw_hash = hash_password(password) if password else None
        sql = (
            f"INSERT INTO homer_users "
            f"(username, display_name, email, locale, password_hash, provider, "
            f" enabled, created_at) "
            f"VALUES ({self._ph(0)}, {self._ph(1)}, {self._ph(2)}, "
            f"{self._ph(3)}, {self._ph(4)}, {self._ph(5)}, {self._ph(6)}, "
            f"{self._ph(7)})"
        )
        self.db.execute(sql, [
            username, display_name, email, locale, pw_hash, provider,
            self._bool(True), now,
        ])
        self.db.commit()

        if self._driver() == 'postgres':
            row = self.db.fetchone(
                f"SELECT id FROM homer_users WHERE username = {self._ph(0)}",
                [username],
            )
            return row[0] if not isinstance(row, dict) else next(iter(row.values()))
        return self.db.execute("SELECT 1", []).lastrowid \
            if self._driver() == 'sqlite' else self._fetch_last_id()

    def _fetch_last_id(self) -> int:
        # Универсальный путь для не-postgres
        row = self.db.fetchone(
            "SELECT id FROM homer_users ORDER BY id DESC LIMIT 1"
        )
        return row[0] if not isinstance(row, dict) else next(iter(row.values()))

    def set_password(self, username: str, password: str):
        self.db.execute(
            f"UPDATE homer_users SET password_hash = {self._ph(0)}, "
            f"updated_at = {self._ph(1)} WHERE username = {self._ph(2)}",
            [hash_password(password), datetime.now(), username],
        )
        self.db.commit()

    def set_enabled(self, username: str, enabled: bool):
        self.db.execute(
            f"UPDATE homer_users SET enabled = {self._ph(0)}, "
            f"updated_at = {self._ph(1)} WHERE username = {self._ph(2)}",
            [self._bool(enabled), datetime.now(), username],
        )
        self.db.commit()

    def delete_user(self, username: str) -> bool:
        u = self.get_user_by_name(username)
        if not u:
            return False
        self.db.execute(
            f"DELETE FROM homer_user_roles WHERE user_id = {self._ph(0)}",
            [u.id],
        )
        self.db.execute(
            f"DELETE FROM homer_sessions WHERE user_id = {self._ph(0)}",
            [u.id],
        )
        self.db.execute(
            f"DELETE FROM homer_users WHERE id = {self._ph(0)}",
            [u.id],
        )
        self.db.commit()
        return True

    def verify_credentials(self, username: str, password: str) -> Optional[User]:
        user = self.get_user_by_name(username)
        if not user or not user.enabled:
            return None
        # Берём hash из БД
        row = self.db.fetchone(
            f"SELECT password_hash FROM homer_users "
            f"WHERE username = {self._ph(0)}",
            [username], dictionary=True,
        )
        if not row:
            return None
        pw_hash = row.get('password_hash') if isinstance(row, dict) else row[0]
        if not pw_hash:
            return None
        if verify_password(password, pw_hash):
            return user
        return None

    def upsert_provider_user(self, username: str, *,
                             provider: str,
                             display_name: str = '',
                             email: str = '') -> User:
        """
        Создаёт или обновляет пользователя, пришедшего из внешнего провайдера
        (LDAP, Kerberos). Пароль не хранится.
        """
        user = self.get_user_by_name(username)
        if user is None:
            uid = self.create_user(
                username, password=None,
                display_name=display_name or username,
                email=email, provider=provider,
            )
            return self.get_user(uid)
        # Обновляем атрибуты
        self.db.execute(
            f"UPDATE homer_users SET display_name = {self._ph(0)}, "
            f"email = {self._ph(1)}, updated_at = {self._ph(2)} "
            f"WHERE id = {self._ph(3)}",
            [display_name or user.display_name, email or user.email,
             datetime.now(), user.id],
        )
        self.db.commit()
        return self.get_user(user.id)

    def _row_to_user(self, row: dict) -> User:
        uid = row['id']
        roles = self.roles_for_user(uid)
        perms = set()
        for role in roles:
            perms.update(self.role_permissions(role))
        return User(
            id=uid,
            username=row['username'],
            display_name=row.get('display_name') or '',
            email=row.get('email') or '',
            locale=row.get("locale") or None,
            provider=row.get('provider') or 'local',
            enabled=bool(row.get('enabled', True)),
            roles=roles,
            permissions=perms,
        )

    # ─────────── Роли ───────────

    def list_roles(self) -> list[dict]:
        rows = self.db.fetchall(
            "SELECT * FROM homer_roles ORDER BY name",
            dictionary=True,
        )
        result = []
        for r in rows:
            perms_raw = r.get('permissions') or '[]'
            try:
                perms = json.loads(perms_raw)
            except Exception:
                perms = []
            result.append({
                'id': r['id'],
                'name': r['name'],
                'display_name': r.get('display_name') or '',
                'permissions': perms,
                'builtin': bool(r.get('builtin', False)),
            })
        return result

    def get_role(self, name: str) -> Optional[dict]:
        for r in self.list_roles():
            if r['name'] == name:
                return r
        return None

    def upsert_role(self, name: str, *, display_name: str = '',
                    permissions: list[str] | None = None,
                    builtin: bool = False) -> int:
        existing = self.get_role(name)
        perms_json = json.dumps(permissions or [], ensure_ascii=False)
        if existing:
            self.db.execute(
                f"UPDATE homer_roles SET display_name = {self._ph(0)}, "
                f"permissions = {self._ph(1)} WHERE id = {self._ph(2)}",
                [display_name, perms_json, existing['id']],
            )
            self.db.commit()
            return existing['id']
        sql = (
            f"INSERT INTO homer_roles (name, display_name, permissions, "
            f"builtin, created_at) "
            f"VALUES ({self._ph(0)}, {self._ph(1)}, {self._ph(2)}, "
            f"{self._ph(3)}, {self._ph(4)})"
        )
        self.db.execute(sql, [
            name, display_name, perms_json, self._bool(builtin),
            datetime.now(),
        ])
        self.db.commit()
        r = self.get_role(name)
        return r['id'] if r else 0

    def delete_role(self, name: str) -> bool:
        r = self.get_role(name)
        if not r or r['builtin']:
            return False
        self.db.execute(
            f"DELETE FROM homer_user_roles WHERE role_id = {self._ph(0)}",
            [r['id']],
        )
        self.db.execute(
            f"DELETE FROM homer_roles WHERE id = {self._ph(0)}",
            [r['id']],
        )
        self.db.commit()
        return True

    def roles_for_user(self, user_id: int) -> list[str]:
        sql = (
            f"SELECT r.name FROM homer_roles r "
            f"JOIN homer_user_roles ur ON ur.role_id = r.id "
            f"WHERE ur.user_id = {self._ph(0)}"
        )
        rows = self.db.fetchall(sql, [user_id], dictionary=True)
        return [r['name'] for r in rows]

    def role_permissions(self, role_name: str) -> list[str]:
        r = self.get_role(role_name)
        if not r:
            return []
        return r['permissions']

    def assign_role(self, user_id: int, role_name: str) -> bool:
        r = self.get_role(role_name)
        if not r:
            return False
        try:
            self.db.execute(
                f"INSERT INTO homer_user_roles (user_id, role_id) "
                f"VALUES ({self._ph(0)}, {self._ph(1)})",
                [user_id, r['id']],
            )
            self.db.commit()
            return True
        except Exception:
            return False

    def revoke_role(self, user_id: int, role_name: str):
        r = self.get_role(role_name)
        if not r:
            return
        self.db.execute(
            f"DELETE FROM homer_user_roles WHERE user_id = {self._ph(0)} "
            f"AND role_id = {self._ph(1)}",
            [user_id, r['id']],
        )
        self.db.commit()

    # ─────────── Сессии ───────────

    def create_session(self, user_id: int, *, lifetime_seconds: int = 86400,
                       ip: str = None, user_agent: str = None) -> str:
        """
        Create a session row and return its id.

        `lifetime_seconds` is coerced to int with a sane default; if the
        value is invalid (None, negative, 0), we fall back to 86400.
        """
        try:
            lifetime_seconds = int(lifetime_seconds)
        except (TypeError, ValueError):
            lifetime_seconds = 86400

        if lifetime_seconds <= 0:
            lifetime_seconds = 86400

        sid = uuid.uuid4().hex
        now = datetime.now()
        expires = now + timedelta(seconds=lifetime_seconds)

        self.db.execute(
            f"INSERT INTO homer_sessions "
            f"(id, user_id, created_at, expires_at, ip, user_agent) "
            f"VALUES ({self._ph(0)}, {self._ph(1)}, {self._ph(2)}, "
            f"{self._ph(3)}, {self._ph(4)}, {self._ph(5)})",
            [sid, user_id, now, expires, ip, user_agent],
        )
        self.db.commit()
        return sid

    def get_session(self, sid: str) -> Optional[User]:
        """
        Return the user for a session id, if the session exists and is
        not expired. Robust against NULL/None timestamps (legacy rows).
        """
        row = self.db.fetchone(
            f"SELECT user_id, expires_at FROM homer_sessions "
            f"WHERE id = {self._ph(0)}",
            [sid], dictionary=True,
        )
        if not row:
            return None

        user_id = row["user_id"] if isinstance(row, dict) else row[0]
        expires = row["expires_at"] if isinstance(row, dict) else row[1]

        # Normalize expires: accept None, str, datetime
        if expires is None:
            # No expiry recorded -- treat as immediately invalid
            self.delete_session(sid)
            return None

        if isinstance(expires, str):
            try:
                expires = datetime.fromisoformat(expires)
            except ValueError:
                # Try SQLite default format
                try:
                    expires = datetime.strptime(expires, "%Y-%m-%d %H:%M:%S")
                except ValueError:
                    self.delete_session(sid)
                    return None

        if not isinstance(expires, datetime):
            # Unknown format -- do not trust this session
            self.delete_session(sid)
            return None

        if expires < datetime.now():
            self.delete_session(sid)
            return None

        return self.get_user(user_id)

    def delete_session(self, sid: str):
        self.db.execute(
            f"DELETE FROM homer_sessions WHERE id = {self._ph(0)}", [sid],
        )
        self.db.commit()

    def purge_expired_sessions(self) -> int:
        """
        Delete expired sessions AND sessions with NULL expires_at.
        Returns the number of deleted rows.
        """
        now = datetime.now()
        # 1) expired
        cur = self.db.execute(
            f"DELETE FROM homer_sessions WHERE expires_at < {self._ph(0)}",
            [now],
        )
        count = cur.rowcount
        # 2) NULL
        try:
            cur2 = self.db.execute(
                "DELETE FROM homer_sessions WHERE expires_at IS NULL"
            )
            count += cur2.rowcount
        except Exception:
            pass
        self.db.commit()
        return count

    def close(self):
        if not self._external_db:
            self.db.close()

    def set_user_locale(self, username: str, locale: Optional[str]) -> bool:
        """
        Set user's preferred locale (or clear it with None).
        Returns True if the user existed.
        """
        user = self.get_user_by_name(username)
        if not user:
            return False
        self.db.execute(
            f"UPDATE homer_users SET locale = {self._ph(0)}, "
            f"updated_at = {self._ph(1)} WHERE id = {self._ph(2)}",
            [locale, datetime.now(), user.id],
        )
        self.db.commit()
        return True

    def update_user(self, username: str, *,
                    display_name: Optional[str] = None,
                    email: Optional[str] = None,
                    enabled: Optional[bool] = None,
                    password: Optional[str] = None,
                    locale: Optional[str] = None) -> bool:
        """
        Update a user. Only non-None fields are touched.

        Note: `locale=None` means "do not change". To explicitly clear
        the locale, use set_user_locale(username, None).
        """
        user = self.get_user_by_name(username)
        if not user:
            return False

        fields: list[str] = []
        params: list[Any] = []

        def _set(col: str, val: Any):
            fields.append(f"{col} = {self._ph(len(params))}")
            params.append(val)

        if display_name is not None:
            _set("display_name", display_name)
        if email is not None:
            _set("email", email)
        if enabled is not None:
            _set("enabled", self._bool(enabled))
        if password:
            _set("password_hash", hash_password(password))
        if locale is not None:
            _set("locale", locale)

        if not fields:
            return True

        fields.append(f"updated_at = {self._ph(len(params))}")
        params.append(datetime.now())

        params.append(user.id)
        sql = (
            f"UPDATE homer_users SET {', '.join(fields)} "
            f"WHERE id = {self._ph(len(params) - 1)}"
        )
        self.db.execute(sql, params)
        self.db.commit()
        return True

    def set_roles(self, user_id: int, roles: list[str]) -> None:
        """
        Replace all roles for a user. Builtin 'admin' cannot be removed by
        this method unless it is explicitly omitted from `roles`.
        """
        # Delete existing
        self.db.execute(
            f"DELETE FROM homer_user_roles WHERE user_id = {self._ph(0)}",
            [user_id],
        )
        self.db.commit()
        # Add new
        for role in roles:
            self.assign_role(user_id, role)

    def user_role_names(self, user_id: int) -> list[str]:
        return self.roles_for_user(user_id)

    def count_admins(self) -> int:
        """Number of enabled users with the 'admin' role."""
        sql = (
            "SELECT COUNT(DISTINCT u.id) AS cnt "
            "FROM homer_users u "
            "JOIN homer_user_roles ur ON ur.user_id = u.id "
            "JOIN homer_roles r ON r.id = ur.role_id "
            "WHERE r.name = 'admin' AND u.enabled = "
            + self._bool(True)
        )
        row = self.db.fetchone(sql, dictionary=True)
        if not row:
            return 0
        return int(row.get("cnt") or 0) if isinstance(row, dict) else int(row[0] or 0)



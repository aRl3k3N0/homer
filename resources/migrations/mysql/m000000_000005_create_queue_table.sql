CREATE TABLE IF NOT EXISTS queue (
    id               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    command          VARCHAR(255)    NOT NULL,
    args             TEXT            NOT NULL,
    priority         INT             NOT NULL DEFAULT 0,
    status           VARCHAR(32)     NOT NULL DEFAULT 'pending',
    result           TEXT            NULL,
    exit_code        INT             NULL,
    error            TEXT            NULL,
    created_at       TIMESTAMP(6)    NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    run_at           TIMESTAMP(6)    NULL,
    started_at       TIMESTAMP(6)    NULL,
    finished_at      TIMESTAMP(6)    NULL,
    parent_job_id    BIGINT UNSIGNED NULL,
    locked_by        VARCHAR(255)    NULL,
    lease_until      TIMESTAMP(6)    NULL,
    run_id           VARCHAR(64)     NULL,
    triggered_by     VARCHAR(255)    NULL,
    attempts         INT             NOT NULL DEFAULT 0,
    max_attempts     INT             NOT NULL DEFAULT 3,
    retry_delay      INT             NOT NULL DEFAULT 60,
    last_attempt_at  TIMESTAMP(6)    NULL,
    cancel_requested TINYINT(1)      NOT NULL DEFAULT 0,
    timeout_sec      INT             NULL,
    PRIMARY KEY (id),
    KEY idx_queue_status   (status),
    KEY idx_queue_priority (priority DESC, id ASC),
    KEY idx_queue_run_at   (run_at),
    KEY idx_queue_parent   (parent_job_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

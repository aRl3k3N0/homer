            command          VARCHAR2(255) NOT NULL,
            args             CLOB DEFAULT ''{}'' NOT NULL,
            priority         NUMBER DEFAULT 0 NOT NULL,
            status           VARCHAR2(32) DEFAULT ''pending'' NOT NULL,
            result           CLOB,
            exit_code        NUMBER,
            error            CLOB,
            created_at       TIMESTAMP NOT NULL,
            run_at           TIMESTAMP,
            started_at       TIMESTAMP,
            finished_at      TIMESTAMP,
            parent_job_id    NUMBER,
            locked_by        VARCHAR2(255),
            lease_until      TIMESTAMP,
            run_id           VARCHAR2(64),
            triggered_by     VARCHAR2(255),
            attempts         NUMBER DEFAULT 0 NOT NULL,
            max_attempts     NUMBER DEFAULT 3 NOT NULL,
            retry_delay      NUMBER DEFAULT 60 NOT NULL,
            last_attempt_at  TIMESTAMP,
            cancel_requested NUMBER(1) DEFAULT 0 NOT NULL,
            timeout_sec      NUMBER
        )';

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE homer_nodes (
            id           VARCHAR2(64) PRIMARY KEY,
            hostname     VARCHAR2(255) NOT NULL,
            ip           VARCHAR2(64),
            started_at   TIMESTAMP NOT NULL,
            last_seen    TIMESTAMP NOT NULL,
            role         VARCHAR2(32) DEFAULT ''worker'' NOT NULL,
            version      VARCHAR2(32),
            meta         CLOB
        )';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE homer_node_commands (
            id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            node_id    VARCHAR2(64) NOT NULL,
            action     VARCHAR2(64) NOT NULL,
            payload    CLOB,
            created_at TIMESTAMP NOT NULL,
            picked_at  TIMESTAMP
        )';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE homer_advisory_locks (
            name        VARCHAR2(255) PRIMARY KEY,
            token       VARCHAR2(64) NOT NULL,
            locked_at   TIMESTAMP NOT NULL,
            expires_at  TIMESTAMP NOT NULL
        )';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;

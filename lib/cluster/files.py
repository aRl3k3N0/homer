"""
Distributed files: keep files in DB, sync to disk on each node.

Every write:
    1. writes to homer_files (new version)
    2. writes a change record to homer_changes
    3. local disk is updated by the writing node

Every node runs a "change watcher" thread that polls homer_changes
and applies changes to its local disk.
"""

from __future__ import annotations

import hashlib
import threading
import time
from datetime import datetime
from pathlib import Path
from typing import Optional

from lib.db import connect, BaseDB



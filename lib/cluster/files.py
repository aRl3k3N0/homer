class ClusterFiles:
    def __init__(self, config, node_id: str, paths, role: str = "worker"):
        self.config = config
        self.node_id = node_id
        self.paths = paths
        self.role = role

        self.db = self._build_db()
        if not self.db.is_connected:
            self.db.connect()
        self._init_schema()

        self._stop = threading.Event()
        self._thread: Optional[threading.Thread] = None
        self._last_change_id = 0
        self._on_change_callbacks: list = []

    def _build_db(self):
        sched_cfg = self.config.get("scheduler", {}) or {}
        driver = sched_cfg.get("storage", "sqlite")
        conn_cfg = sched_cfg.get(driver) or self.config.get(f"databases.{driver}")
        if driver == "sqlite":
            if not conn_cfg:
                conn_cfg = {"path": "var/cache/homer.db"}
            elif "path" not in conn_cfg:
                conn_cfg = dict(conn_cfg, path="var/cache/homer.db")
        return connect(driver, conn_cfg)

    def _driver(self):
        return self.db.driver_name

    def _ph(self, idx):
        style = self.db._placeholder_style
        if style == ":name":
            return f":{idx + 1}"
        if style == "?":
            return "?"
        return "%s"

    def _init_schema(self):
        ddl = DDL.get(self._driver())
        if ddl:
            if self._driver() == "oracle":
                for block in ddl.split(";"):
                    block = block.strip()
                    if not block:
                        continue
                    cur = self.db.cursor()
                    try: cur.execute(block)
                    except Exception: pass
                    finally:
                        try: cur.close()
                        except Exception: pass
            else:
                for stmt in [s.strip() for s in ddl.split(";") if s.strip()]:
                    try: self.db.execute(stmt)
                    except Exception: pass
            self.db.commit()

    # ─────────── Write (only primary) ───────────

    def write(self, category: str, rel_path: str, content: str,
              author: str) -> int:
        """
        Store the file in DB, bump its version, record the change.
        Returns the new version number.
        """
        blob = content.encode("utf-8")
        checksum = hashlib.sha256(blob).hexdigest()
        key = f"{category}:{rel_path}"

        current = self._get(key)
        new_version = (current["version"] + 1) if current else 1

        if current:
            self.db.execute(
                f"UPDATE homer_files SET checksum = {self._ph(0)}, "
                f"content = {self._ph(1)}, version = {self._ph(2)}, "
                f"updated_at = {self._ph(3)}, updated_by = {self._ph(4)} "
                f"WHERE path = {self._ph(5)}",
                [checksum, blob, new_version, datetime.now(), author, key],
            )
        else:
            self.db.execute(
                f"INSERT INTO homer_files "
                f"(path, category, checksum, content, version, updated_at, updated_by) "
                f"VALUES ({self._ph(0)}, {self._ph(1)}, {self._ph(2)}, "
                f"{self._ph(3)}, {self._ph(4)}, {self._ph(5)}, {self._ph(6)})",
                [key, category, checksum, blob, new_version,
                 datetime.now(), author],
            )
        self.db.commit()

        self._record_change(category, rel_path, new_version, "write", author)
        return new_version

    def delete(self, category: str, rel_path: str, author: str) -> int:
        key = f"{category}:{rel_path}"
        current = self._get(key)
        new_version = (current["version"] + 1) if current else 1
        self.db.execute(
            f"DELETE FROM homer_files WHERE path = {self._ph(0)}", [key],
        )
        self.db.commit()
        self._record_change(category, rel_path, new_version, "delete", author)
        return new_version

    def _record_change(self, category, rel_path, version, action, author):
        key = f"{category}:{rel_path}"
        self.db.execute(
            f"INSERT INTO homer_changes "
            f"(path, category, version, action, author, ts, node_id) "
            f"VALUES ({self._ph(0)}, {self._ph(1)}, {self._ph(2)}, "
            f"{self._ph(3)}, {self._ph(4)}, {self._ph(5)}, {self._ph(6)})",
            [key, category, version, action, author,
             datetime.now(), self.node_id],
        )
        self.db.commit()

    # ─────────── Sync ───────────

    def start_watcher(self, interval: float = 3.0):
        if self._thread and self._thread.is_alive():
            return
        self._stop.clear()
        self._thread = threading.Thread(
            target=self._loop, name="homer-files-watcher", daemon=True,
        )
        self._last_change_id = self._max_change_id()
        self._thread.start()
        _ = interval

    def stop_watcher(self):
        self._stop.set()
        if self._thread:
            self._thread.join(timeout=2)
            self._thread = None

    def on_change(self, cb):
        """cb(category, rel_path, action) called on each remote change."""
        self._on_change_callbacks.append(cb)

    def _loop(self):
        while not self._stop.wait(3):
            try:
                changes = self._poll_changes()
                for ch in changes:
                    self._apply_change(ch)
                    for cb in self._on_change_callbacks:
                        try:
                            cb(ch["category"], ch["rel_path"], ch["action"])
                        except Exception:
                            pass
            except Exception:
                pass

    def _poll_changes(self) -> list[dict]:
        rows = self.db.fetchall(
            f"SELECT * FROM homer_changes WHERE id > {self._ph(0)} "
            f"ORDER BY id ASC",
            [self._last_change_id], dictionary=True,
        )
        out = []
        for r in rows:
            d = dict(r) if not isinstance(r, dict) else r
            path = d["path"]
            if ":" not in path:
                continue
            cat, rel = path.split(":", 1)
            out.append({
                "id": d["id"],
                "category": cat,
                "rel_path": rel,
                "version": d["version"],
                "action": d["action"],
                "author": d["author"],
            })
            self._last_change_id = max(self._last_change_id, d["id"])
        return out

    def _apply_change(self, change: dict):
        """Pull the latest content and write it to local disk."""
        category = change["category"]
        rel_path = change["rel_path"]
        action = change["action"]

        local = self._local_path(category, rel_path)
        if local is None:
            return

        if action == "delete":
            try:
                if local.exists():
                    local.unlink()
            except Exception:
                pass
            return

        key = f"{category}:{rel_path}"
        row = self.db.fetchone(
            f"SELECT content FROM homer_files WHERE path = {self._ph(0)}",
            [key], dictionary=True,
        )
        if not row:
            return
        blob = row["content"] if isinstance(row, dict) else row[0]
        if isinstance(blob, str):
            blob = blob.encode("utf-8")
        content = bytes(blob).decode("utf-8", errors="replace")

        # Skip if the same content already on disk
        try:
            current = local.read_text(encoding="utf-8") if local.exists() else ""
            if current == content:
                return
        except Exception:
            pass

        local.parent.mkdir(parents=True, exist_ok=True)
        tmp = local.with_suffix(local.suffix + ".tmp")
        tmp.write_text(content, encoding="utf-8")
        tmp.replace(local)

    def _local_path(self, category: str, rel_path: str) -> Optional[Path]:
        roots = {
            "config":    self.paths.config_path.parent,
            "commands":  self.paths.commands_dir,
            "plugins":   self.paths.plugins_dir,
            "langs":     self.paths.langs_dir,
            "templates": self.paths.templates_dir,
            "static":    self.paths.static_dir,
            "email":     self.paths.email_templates_dir,
        }
        root = roots.get(category)
        if not root:
            return None
        return root / rel_path

    def _max_change_id(self) -> int:
        row = self.db.fetchone(
            "SELECT COALESCE(MAX(id), 0) AS m FROM homer_changes",
            dictionary=True,
        )
        if not row:
            return 0
        return int(row.get("m") or 0) if isinstance(row, dict) else int(row[0] or 0)

    def _get(self, key: str) -> Optional[dict]:
        row = self.db.fetchone(
            f"SELECT * FROM homer_files WHERE path = {self._ph(0)}",
            [key], dictionary=True,
        )
        return dict(row) if row else None

    def initial_sync(self):
        """
        On startup: pull all files from DB and write them to disk
        if the local versions differ.
        """
        rows = self.db.fetchall(
            "SELECT path, content FROM homer_files", dictionary=True,
        )
        for r in rows:
            d = dict(r) if not isinstance(r, dict) else r
            path = d["path"]
            if ":" not in path:
                continue
            cat, rel = path.split(":", 1)
            self._apply_change({
                "category": cat,
                "rel_path": rel,
                "action": "write",
            })

"""
Editor history: snapshots of files and config keys.

Table:
    homer_editor_history
        id          PK
        ts          when the change was made
        user        who made it
        category    'file' | 'config'
        target      'commands:hello.py' | 'databases.postgres.host'
        action      'write' | 'delete' | 'rename' | 'set'
        before      previous content/value
        after       new content/value
        checksum    sha256 of `after`
        source      source file path if known

Rollback restores the `before` content.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import datetime
from typing import Any, Optional

from lib.db import connect, BaseDB, DBError



@dataclass
class HistoryEntry:
    id: int
    ts: datetime
    user: str
    category: str
    target: str
    action: str
    before: Optional[str]
    after: Optional[str]
    checksum: Optional[str]
    source: Optional[str]


class EditorHistory:
    def __init__(self, config, db: Optional[BaseDB] = None):
        self.config = config
        self._external_db = db is not None
        self.db = db or self._build_db()
        if not self.db.is_connected:
            self.db.connect()
        self._init_schema()

    def _build_db(self):
        sched_cfg = self.config.get("scheduler", {}) or {}
        driver = sched_cfg.get("storage", "sqlite")
        conn_cfg = sched_cfg.get(driver) or self.config.get(f"databases.{driver}")
        if driver == "sqlite":
            if not conn_cfg:
                conn_cfg = {"path": "var/cache/homer.db"}
            elif "path" not in conn_cfg:
                conn_cfg = dict(conn_cfg, path="var/cache/homer.db")
        return connect(driver, conn_cfg)

    def _driver(self):
        return self.db.driver_name

    def _ph(self, idx):
        style = self.db._placeholder_style
        if style == ":name":
            return f":{idx + 1}"
        if style == "?":
            return "?"
        return "%s"

    def _init_schema(self):
        ddl = DDL.get(self._driver())
        if not ddl:
            raise DBError(f"No DDL for {self._driver()}")
        if self._driver() == "oracle":
            cur = self.db.cursor()
            try:
                cur.execute(ddl)
            except Exception:
                pass
            finally:
                try: cur.close()
                except Exception: pass
        else:
            for stmt in [s.strip() for s in ddl.split(";") if s.strip()]:
                try:
                    self.db.execute(stmt)
                except Exception:
                    pass
        self.db.commit()

    # ─────────── Write ───────────

    def record(self, *, user: str, category: str, target: str,
               action: str, before: Optional[str], after: Optional[str],
               source: Optional[str] = None) -> int:
        checksum = None
        if after is not None:
            h = hashlib.sha256()
            h.update(after.encode("utf-8"))
            checksum = h.hexdigest()

        sql = (
            f"INSERT INTO homer_editor_history "
            f"(ts, user_name, category, target, action, before, after, checksum, source) "
            f"VALUES ({self._ph(0)}, {self._ph(1)}, {self._ph(2)}, "
            f"{self._ph(3)}, {self._ph(4)}, {self._ph(5)}, {self._ph(6)}, "
            f"{self._ph(7)}, {self._ph(8)})"
        )
        self.db.execute(sql, [
            datetime.now(), user, category, target, action,
            before, after, checksum, source,
        ])
        self.db.commit()

        if self._driver() == "postgres":
            row = self.db.fetchone(
                "SELECT id FROM homer_editor_history ORDER BY id DESC LIMIT 1"
            )
            return row[0] if not isinstance(row, dict) else next(iter(row.values()))
        return 0

    # ─────────── Read ───────────

    def list(self, category: Optional[str] = None,
             target: Optional[str] = None,
             limit: int = 100) -> list[HistoryEntry]:
        where = []
        params = []
        if category:
            where.append(f"category = {self._ph(len(params))}")
            params.append(category)
        if target:
            where.append(f"target = {self._ph(len(params))}")
            params.append(target)
        where_sql = "WHERE " + " AND ".join(where) if where else ""
        sql = (
            f"SELECT * FROM homer_editor_history {where_sql} "
            f"ORDER BY id DESC LIMIT {int(limit)}"
        )
        rows = self.db.fetchall(sql, params or None, dictionary=True)
        return [self._row(r) for r in rows]

    def get(self, entry_id: int) -> Optional[HistoryEntry]:
        row = self.db.fetchone(
            f"SELECT * FROM homer_editor_history WHERE id = {self._ph(0)}",
            [entry_id], dictionary=True,
        )
        return self._row(row) if row else None

    def close(self):
        if not self._external_db:
            self.db.close()

    def _row(self, row) -> HistoryEntry:
        d = dict(row) if not isinstance(row, dict) else row

        def _dt(v):
            if isinstance(v, datetime):
                return v
            if isinstance(v, str):
                try: return datetime.fromisoformat(v)
                except ValueError: pass
            return v

        return HistoryEntry(
            id=d["id"],
            ts=_dt(d["ts"]),
            user=d["user_name"],
            category=d["category"],
            target=d["target"],
            action=d["action"],
            before=d.get("before"),
            after=d.get("after"),
            checksum=d.get("checksum"),
            source=d.get("source"),
        )

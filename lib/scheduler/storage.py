class DBStorage(BaseStorage):
    def __init__(self, config, db: Optional[BaseDB] = None):
        self.config = config
        self._external_db = db is not None
        self.db = db or self._build_db()
        if not self.db.is_connected:
            self.db.connect()
        self.init_schema()
        self._current_run_id = {}

    def _build_db(self):
        sched_cfg = self.config.get('scheduler', {}) or {}
        driver = sched_cfg.get('storage', 'sqlite')
        conn_cfg = sched_cfg.get(driver) or self.config.get(f'databases.{driver}')
        if driver == 'sqlite':
            if not conn_cfg:
                conn_cfg = {'path': 'var/scheduler.db'}
            elif 'path' not in conn_cfg:
                conn_cfg = dict(conn_cfg, path='var/scheduler.db')
        return connect(driver, conn_cfg)

    def _driver(self):
        return self.db.driver_name

    def _ph(self, idx):
        style = self.db._placeholder_style
        if style == ':name':
            return f':{idx + 1}'
        if style == '?':
            return '?'
        return '%s'

    def _ph_list(self, n):
        return ', '.join(self._ph(i) for i in range(n))

    def _host_id(self):
        return f"{socket.gethostname()}:{os.getpid()}"

    def _bool(self, v):
        return 1 if v else 0 if self._driver() == 'oracle' else bool(v)

    def init_schema(self):
        driver = self._driver()
        ddl = DDL.get(driver)
        if not ddl:
            raise DBError(f"Нет DDL для драйвера '{driver}'")
        if driver == 'oracle':
            cur = self.db.cursor()
            try:
                cur.execute(ddl)
            finally:
                try: cur.close()
                except Exception: pass
        else:
            for stmt in [s.strip() for s in ddl.split(';') if s.strip()]:
                self.db.execute(stmt)
        self.db.commit()

    def add(self, task):
        sql = (f"INSERT INTO homer_tasks "
               f"(name, command, args, cron, enabled, description) "
               f"VALUES ({self._ph_list(6)})")
        cur = self.db.execute(sql, [
            task.name, task.command, task.args_json(), task.cron,
            self._bool(task.enabled), task.description,
        ])
        self.db.commit()
        if self._driver() == 'postgres':
            row = self.db.fetchone(
                f"SELECT id FROM homer_tasks WHERE name = {self._ph(0)}",
                [task.name]
            )
            return row[0] if not isinstance(row, dict) else next(iter(row.values()))
        return cur.lastrowid

    def get(self, task_id):
        row = self.db.fetchone(
            f"SELECT * FROM homer_tasks WHERE id = {self._ph(0)}",
            [task_id], dictionary=True,
        )
        return Task.from_row(row) if row else None

    def get_by_name(self, name):
        row = self.db.fetchone(
            f"SELECT * FROM homer_tasks WHERE name = {self._ph(0)}",
            [name], dictionary=True,
        )
        return Task.from_row(row) if row else None

    def list(self):
        rows = self.db.fetchall(
            "SELECT * FROM homer_tasks ORDER BY name", dictionary=True,
        )
        return [Task.from_row(r) for r in rows]

    def update(self, task):
        sql = (
            f"UPDATE homer_tasks SET "
            f"name = {self._ph(0)}, command = {self._ph(1)}, "
            f"args = {self._ph(2)}, cron = {self._ph(3)}, "
            f"enabled = {self._ph(4)}, description = {self._ph(5)}, "
            f"last_run = {self._ph(6)}, last_status = {self._ph(7)}, "
            f"last_error = {self._ph(8)}, next_run = {self._ph(9)} "
            f"WHERE id = {self._ph(10)}"
        )
        self.db.execute(sql, [
            task.name, task.command, task.args_json(), task.cron,
            self._bool(task.enabled), task.description,
            task.last_run, task.last_status, task.last_error,
            task.next_run, task.id,
        ])
        self.db.commit()

    def remove(self, task_id):
        self.db.execute(
            f"DELETE FROM homer_tasks WHERE id = {self._ph(0)}", [task_id]
        )
        self.db.commit()

    def acquire_task(self, task_id, lease_seconds=300):
        now = datetime.now()
        lease_until = now + timedelta(seconds=lease_seconds)
        run_id = str(uuid.uuid4())
        locked_by = self._host_id()

        sql = (
            f"UPDATE homer_tasks SET "
            f"  locked_by = {self._ph(0)}, "
            f"  lease_until = {self._ph(1)}, "
            f"  run_id = {self._ph(2)}, "
            f"  heartbeat_at = {self._ph(3)}, "
            f"  last_status = {self._ph(4)}, "
            f"  last_run = {self._ph(5)} "
            f"WHERE id = {self._ph(6)} AND enabled = {self._ph(7)} "
            f"  AND (lease_until IS NULL OR lease_until < {self._ph(8)})"
        )
        params = [locked_by, lease_until, run_id, now, 'running', now,
                  task_id, self._bool(True), now]
        cur = self.db.execute(sql, params)
        self.db.commit()
        if cur.rowcount == 1:
            self._current_run_id[task_id] = run_id
            return True
        return False

    def heartbeat(self, task_id, run_id, lease_seconds=300):
        now = datetime.now()
        lease_until = now + timedelta(seconds=lease_seconds)
        cur = self.db.execute(
            f"UPDATE homer_tasks SET heartbeat_at = {self._ph(0)}, "
            f"lease_until = {self._ph(1)} "
            f"WHERE id = {self._ph(2)} AND run_id = {self._ph(3)}",
            [now, lease_until, task_id, run_id],
        )
        self.db.commit()
        return cur.rowcount == 1

    def release_task(self, task_id, run_id, status='done', error=None):
        self.db.execute(
            f"UPDATE homer_tasks SET "
            f"  last_status = {self._ph(0)}, "
            f"  last_error = {self._ph(1)}, "
            f"  locked_by = NULL, lease_until = NULL, "
            f"  run_id = NULL, heartbeat_at = NULL "
            f"WHERE id = {self._ph(2)} AND run_id = {self._ph(3)}",
            [status, error, task_id, run_id],
        )
        self.db.commit()

    def close(self):
        if not self._external_db:
            self.db.close()
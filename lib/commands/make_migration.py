"""
make:migration — создать новую миграцию для плагина.
"""
import re
from datetime import datetime
from pathlib import Path

from lib.console import console, Color

DESCRIPTION = "Создать файл миграции для плагина"


# ─────────── Шаблоны ───────────

TEMPLATES = {
    'empty': """-- Migration: {name}
-- Plugin:    {plugin}
-- Driver:    {driver}
-- Created:   {created}

-- Ваш SQL здесь. Один стейтмент — один ; в конце.
-- Пример:
--   CREATE TABLE {plugin}_data (
--       id INTEGER PRIMARY KEY,
--       name TEXT NOT NULL
--   );

""",
    'create_table': """-- Migration: {name}
-- Plugin:    {plugin}
-- Driver:    {driver}
-- Created:   {created}

CREATE TABLE {plugin}_{table_name} (
    id          {pk_type},
    created_at  {ts_type} NOT NULL,
    updated_at  {ts_type}
{extra_columns}
);
{idxs}
""",
    'add_column': """-- Migration: {name}
-- Plugin:    {plugin}
-- Driver:    {driver}
-- Created:   {created}

ALTER TABLE {plugin}_{table_name}
    ADD COLUMN {column_name} {column_type};
""",
    'add_index': """-- Migration: {name}
-- Plugin:    {plugin}
-- Driver:    {driver}
-- Created:   {created}

CREATE INDEX {plugin}_{table_name}_{column_name}_idx
    ON {plugin}_{table_name} ({column_name});
""",
}

PK_TYPES = {
    'sqlite':   ('INTEGER PRIMARY KEY AUTOINCREMENT', 'TEXT'),
    'postgres': ('SERIAL PRIMARY KEY', 'TIMESTAMP'),
    'oracle':   ('NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'TIMESTAMP'),
    'mysql':    ('INT AUTO_INCREMENT PRIMARY KEY', 'DATETIME'),
}


def execute(context):
    args = context['args']
    root = Path(context['root_dir'])

    plugin = args.get('plugin')
    name = args.get('name') or args.get('_positional', [None])[0]
    driver = args.get('driver') or context['config'].get(
        'scheduler.storage', 'sqlite',
    )
    template = args.get('template', 'empty')
    table = args.get('table')
    column = args.get('column')
    ctype = args.get('type', 'TEXT')

    if not plugin or not name:
        console.error("Использование:")
        console.comment("  homer make:migration --plugin=my_plugin "
                        "--name=add_users_table [--driver=sqlite]")
        console.comment("  homer make:migration --plugin=my_plugin "
                        "--name=create_posts --template=create_table "
                        "--table=posts")
        return 1

    if template not in TEMPLATES:
        console.error(f"Неизвестный шаблон '{template}'. "
                      f"Доступные: {', '.join(TEMPLATES)}")
        return 1

    plugin_dir = root / 'plugins' / plugin
    if not plugin_dir.exists():
        console.error(f"Плагин '{plugin}' не найден в plugins/")
        return 1

    mig_dir = plugin_dir / 'migrations' / driver
    mig_dir.mkdir(parents=True, exist_ok=True)

    # Следующий номер
    numbers = []
    for f in mig_dir.glob('*.sql'):
        if f.name == 'uninstall.sql':
            continue
        m = re.match(r'^(\d+)', f.name)
        if m:
            numbers.append(int(m.group(1)))
    next_num = (max(numbers) + 1) if numbers else 1

    # Слаг
    slug = re.sub(r'[^a-z0-9_]+', '_', name.lower()).strip('_')
    filename = f"{next_num:03d}_{slug}.sql"
    target = mig_dir / filename

    if target.exists():
        console.error(f"Файл уже существует: {target}")
        return 1

    # Разворачиваем шаблон
    pk_type, ts_type = PK_TYPES.get(driver, PK_TYPES['sqlite'])
    content = TEMPLATES[template].format(
        name=name,
        plugin=plugin,
        driver=driver,
        created=datetime.now().strftime('%Y-%m-%d %H:%M'),
        table_name=table or 'data',
        column_name=column or 'new_col',
        column_type=ctype,
        pk_type=pk_type,
        ts_type=ts_type,
        extra_columns='',
        idxs='',
    )

    target.write_text(content, encoding='utf-8')

    console.success(f"Создана миграция: {target.relative_to(root)}")
    console.key_value('Плагин', plugin)
    console.key_value('Драйвер', driver)
    console.key_value('Шаблон', template)
    console.comment(f"Применить: homer plugin:migrate --name={plugin}")
    return 0

"""Create a numbered project or plugin SQL migration."""

import re
from datetime import datetime
from pathlib import Path

from lib.console import console
from lib.migrations import SUPPORTED_DRIVERS
from lib.migrations.sql import normalize_driver

DESCRIPTION = 'Создать файл миграции проекта или плагина'


# ─────────── Шаблоны ───────────

TEMPLATES = {
    'empty': """-- Migration: {name}
-- Scope:     {scope}
-- Driver:    {driver}
-- Created:   {created}

-- Ваш SQL здесь. Один стейтмент — один ; в конце.
-- Пример:
--   CREATE TABLE {table_prefix}data (
--       id INTEGER PRIMARY KEY,
--       name TEXT NOT NULL
--   );

""",
    'create_table': """-- Migration: {name}
-- Scope:     {scope}
-- Driver:    {driver}
-- Created:   {created}

CREATE TABLE {table_prefix}{table_name} (
    id          {pk_type},
    created_at  {ts_type} NOT NULL,
    updated_at  {ts_type}
{extra_columns}
);
{idxs}
""",
    'add_column': """-- Migration: {name}
-- Scope:     {scope}
-- Driver:    {driver}
-- Created:   {created}

ALTER TABLE {table_prefix}{table_name}
    ADD COLUMN {column_name} {column_type};
""",
    'add_index': """-- Migration: {name}
-- Scope:     {scope}
-- Driver:    {driver}
-- Created:   {created}

CREATE INDEX {table_prefix}{table_name}_{column_name}_idx
    ON {table_prefix}{table_name} ({column_name});
""",
}

PK_TYPES = {
    'sqlite': ('INTEGER PRIMARY KEY AUTOINCREMENT', 'TEXT'),
    'postgres': ('SERIAL PRIMARY KEY', 'TIMESTAMP'),
    'oracle': ('NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'TIMESTAMP'),
    'mysql': ('INT AUTO_INCREMENT PRIMARY KEY', 'DATETIME'),
}
PK_TYPES['postgresql'] = PK_TYPES['postgres']
PK_TYPES['mariadb'] = PK_TYPES['mysql']


def execute(context):
    args = context['args']
    root = Path(context['root_dir'])

    plugin = args.get('plugin')
    name = args.get('name') or args.get('_positional', [None])[0]
    driver = args.get('driver') or context['config'].get(
        'scheduler.storage',
        'sqlite',
    )
    template = args.get('template', 'empty')
    table = args.get('table')
    column = args.get('column')
    ctype = args.get('type', 'TEXT')

    if not name:
        console.error("Использование:")
        console.comment('  homer make:migration --name=add_users_table [--driver=sqlite]')
        console.comment(
            '  homer make:migration --plugin=my_plugin --name=create_posts '
            '--template=create_table --table=posts'
        )
        return 1

    driver = str(driver).lower()
    if driver not in SUPPORTED_DRIVERS:
        console.error(f"Драйвер '{driver}' не поддерживает SQL-миграции")
        return 1

    if template not in TEMPLATES:
        console.error(f"Неизвестный шаблон '{template}'. Доступные: {', '.join(TEMPLATES)}")
        return 1

    if plugin and not re.fullmatch(r'[A-Za-z0-9_-]+', plugin):
        console.error('Имя плагина содержит недопустимые символы')
        return 1
    if plugin:
        plugin_dir = root / 'plugins' / plugin
        if not plugin_dir.is_dir():
            console.error(f"Плагин '{plugin}' не найден в plugins/")
            return 1
        mig_dir = plugin_dir / 'migrations' / driver
        scope = f'plugin:{plugin}'
        table_prefix = f'{plugin}_'
    else:
        driver = normalize_driver(driver)
        mig_dir = root / 'migrations' / driver
        scope = 'project'
        table_prefix = ''

    for identifier, value in (('table', table), ('column', column)):
        if value and not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', value):
            console.error(f"Некорректный SQL-идентификатор {identifier}: {value}")
            return 1

    slug = re.sub(r'[^a-z0-9_]+', '_', name.lower()).strip('_')
    if not slug:
        console.error('Имя миграции должно содержать латинские буквы или цифры')
        return 1

    mig_dir.mkdir(parents=True, exist_ok=True)

    # Следующий номер
    numbers = []
    for f in mig_dir.glob('*.sql'):
        if f.name == 'uninstall.sql':
            continue
        m = re.match(r'^(\d+)', f.name)
        if m:
            numbers.append(int(m.group(1)))
    next_num = (max(numbers) + 1) if numbers else 1

    # Слаг
    filename = f"{next_num:03d}_{slug}.sql"
    target = mig_dir / filename

    if target.exists():
        console.error(f"Файл уже существует: {target}")
        return 1

    # Разворачиваем шаблон
    pk_type, ts_type = PK_TYPES[driver]
    content = TEMPLATES[template].format(
        name=name,
        plugin=plugin or '',
        scope=scope,
        table_prefix=table_prefix,
        driver=driver,
        created=datetime.now().strftime('%Y-%m-%d %H:%M'),
        table_name=table or 'data',
        column_name=column or 'new_col',
        column_type=ctype,
        pk_type=pk_type,
        ts_type=ts_type,
        extra_columns='',
        idxs='',
    )

    target.write_text(content, encoding='utf-8')

    console.success(f"Создана миграция: {target.relative_to(root)}")
    console.key_value('Область', scope)
    console.key_value('Драйвер', driver)
    console.key_value('Шаблон', template)
    if plugin:
        console.comment(f"Применить: homer plugin:migrate --name={plugin}")
    else:
        console.comment('Применить: homer migrate')
    return 0
